function gf(id, label, name, group, extra = {}) {
  const face = /[\s\d]/.test(name) ? `"${name}"` : name;
  const fallback = extra.fallback
    || (group === 'Serif' ? 'serif' : group === 'Mono' ? 'monospace' : extra.script ? 'cursive' : 'sans-serif');
  return {
    id,
    label,
    family: `${face}, Lexend, ${fallback}`,
    href: extra.href ?? `${name.replace(/ /g, '+')}:wght@400;700`,
    group,
  };
}

