import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { generateKeyPairSync } from 'node:crypto';
import { createDeviceLinks } from '../server/deviceLinks.mjs';

const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys = ON; CREATE TABLE users (id INTEGER PRIMARY KEY); INSERT INTO users VALUES (1), (2)');
let time = Date.now();
const links = createDeviceLinks(db, () => time);
const publicKey = generateKeyPairSync('ec', { namedCurve: 'prime256v1' }).publicKey.export({ format: 'jwk' });
const request = links.create(1, { publicKey });
assert.equal(links.read(1, request.id).status, 'pending');
assert.throws(() => links.read(2, request.id), e => e.status === 410, 'other accounts must not access a request');
assert.throws(() => links.read(1, request.id, 'x'.repeat(43)), e => e.status === 403);
assert.throws(() => links.create(1, { publicKey: { ...publicKey, d: 'secret' } }), e => e.status === 400);
assert.throws(() => links.create(1, { publicKey: { ...publicKey, x: 'A'.repeat(43), y: 'A'.repeat(43) } }), e => e.status === 400);
const envelope = { version: 1, iv: 'A'.repeat(16), ciphertext: 'B'.repeat(80), publicKey };
links.approve(1, request.id, { envelope });
assert.equal(links.read(1, request.id).envelope, undefined, 'approval page cannot read the encrypted handoff');
assert.deepEqual(links.read(1, request.id, request.claimToken).envelope, envelope);
assert.throws(() => links.approve(1, request.id, { envelope }), e => e.status === 409);
links.complete(1, request.id, request.claimToken);
assert.equal(links.read(1, request.id, request.claimToken).envelope, null);
assert.throws(() => links.complete(1, request.id, request.claimToken), e => e.status === 409, 'request is single use');
const qr = links.create(1, { mode: 'qr' });
links.approve(1, qr.id, { envelope });
assert.equal(links.read(1, qr.id, qr.claimToken).envelope.publicKey, undefined);
time += 600_001;
assert.throws(() => links.read(1, qr.id, qr.claimToken), e => e.status === 410);
const canceled = links.create(1, { publicKey });
links.cancel(1, canceled.id);
assert.throws(() => links.approve(1, canceled.id, { envelope }), e => e.status === 409);
db.prepare('DELETE FROM users WHERE id = 1').run();
assert.equal(db.prepare('SELECT COUNT(*) AS count FROM e2ee_device_links').get().count, 0, 'account deletion removes link secrets');
db.close();
console.log('Device link account isolation, key validation, expiry, cancellation, and single-use tests passed.');
