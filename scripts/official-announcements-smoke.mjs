import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { createOfficialAnnouncements } from '../server/officialAnnouncements.mjs';

const db = new DatabaseSync(':memory:', { enableForeignKeyConstraints: true });
db.exec(`
  CREATE TABLE users(id INTEGER PRIMARY KEY, username TEXT);
  CREATE TABLE platform_settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
  CREATE TABLE servers(id INTEGER PRIMARY KEY,name TEXT,owner_id INTEGER REFERENCES users(id) ON DELETE CASCADE,created_at TEXT,description TEXT,is_public INTEGER);
  CREATE TABLE server_roles(id INTEGER PRIMARY KEY,server_id INTEGER REFERENCES servers(id) ON DELETE CASCADE,name TEXT,color TEXT,permissions TEXT,position INTEGER,permission_flags TEXT);
  CREATE TABLE server_channels(id INTEGER PRIMARY KEY,server_id INTEGER REFERENCES servers(id) ON DELETE CASCADE,name TEXT,kind TEXT,voice INTEGER,channel_kind TEXT,locked INTEGER,slowmode INTEGER,topic TEXT,position INTEGER);
  CREATE TABLE server_members(server_id INTEGER REFERENCES servers(id) ON DELETE CASCADE,user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,role_id INTEGER REFERENCES server_roles(id),joined_at TEXT,PRIMARY KEY(server_id,user_id));
  CREATE TABLE server_bans(server_id INTEGER,user_id INTEGER,reason TEXT,created_at TEXT,created_by INTEGER,PRIMARY KEY(server_id,user_id));
  INSERT INTO users VALUES(2,'Alice'),(3,'Bob');
`);
const service = createOfficialAnnouncements(db);
assert.equal(service.ensureAll(), null);
db.exec("INSERT INTO users VALUES(1,'Nuper')");
const id = service.ensureAll();
assert.equal(db.prepare('SELECT count(*) n FROM server_members WHERE server_id=?').get(id).n, 3);
const channel = db.prepare("SELECT * FROM server_channels WHERE server_id=? AND name='announcements'").get(id);
assert.equal(channel.name, 'announcements');
assert.equal(channel.channel_kind, 'announcement');
assert.equal(channel.locked, 1);
assert.equal(db.prepare("SELECT locked FROM server_channels WHERE server_id=? AND name='general' AND voice=0").get(id).locked, 0);
assert.equal(db.prepare("SELECT locked FROM server_channels WHERE server_id=? AND name='voice' AND voice=1").get(id).locked, 0);
assert.equal(service.canPost(1), true);
assert.equal(service.canPost(2), false);
db.exec("INSERT INTO users VALUES(4,'NewMember')");
service.enroll(4);
assert.equal(db.prepare('SELECT count(*) n FROM server_members WHERE server_id=?').get(id).n, 4);
assert.equal(service.kick(4, 1, '2026-10-07T12:00:00.000Z'), true);
db.prepare('DELETE FROM server_members WHERE server_id=? AND user_id=?').run(id, 4);
service.ensureAll();
assert.equal(db.prepare('SELECT 1 FROM server_members WHERE server_id=? AND user_id=?').get(id, 4), undefined, 'A kicked user must not be re-enrolled during bootstrap.');
assert.equal(service.enroll(4), false, 'A kicked user must stay out during automatic enrollment.');
assert.equal(service.clearKick(4), true);
assert.equal(service.enroll(4), true, 'Clearing a kick lets an invited user rejoin.');
db.prepare('INSERT INTO server_bans(server_id,user_id,reason,created_at,created_by) VALUES(?,?,?,?,?)').run(id, 4, 'test', '2026-10-07T12:01:00.000Z', 1);
db.prepare('DELETE FROM server_members WHERE server_id=? AND user_id=?').run(id, 4);
service.ensureAll();
assert.equal(db.prepare('SELECT 1 FROM server_members WHERE server_id=? AND user_id=?').get(id, 4), undefined, 'A banned user must not be re-enrolled during bootstrap.');
db.prepare('DELETE FROM server_bans WHERE server_id=? AND user_id=?').run(id, 4);
assert.equal(service.enroll(4), true, 'An unbanned user can be returned to the required official server.');
const restarted = createOfficialAnnouncements(db);
assert.equal(restarted.ensureAll(), id);
assert.equal(db.prepare('SELECT count(*) n FROM servers').get().n, 1);
assert.equal(db.prepare('SELECT count(*) n FROM server_channels').get().n, 3);
assert.equal(db.prepare('SELECT count(*) n FROM server_roles').get().n, 2);
db.prepare("DELETE FROM server_channels WHERE server_id=? AND name='voice'").run(id);
restarted.ensureAll();
assert.equal(db.prepare('SELECT count(*) n FROM server_channels').get().n, 2, 'Deleted optional voice channel should not reappear');
// Simulate upgrading an existing announcements-only official server.
db.prepare("DELETE FROM server_channels WHERE server_id=? AND name='general'").run(id);
db.prepare("DELETE FROM platform_settings WHERE key='official_community_channels_v1'").run();
assert.equal(restarted.ensureAll(), id);
assert.equal(db.prepare('SELECT count(*) n FROM server_channels').get().n, 3);
assert.equal(db.prepare("SELECT id FROM server_channels WHERE server_id=? AND name='announcements'").get(id).id, channel.id);
assert.equal(db.prepare('SELECT count(*) n FROM server_members WHERE server_id=?').get(id).n, 4);
// Account deletion may cascade the reserved server. A reused SQLite ID must not
// convert an unrelated server into the official one or break later signups.
db.exec("DELETE FROM users WHERE id=1");
db.prepare('INSERT INTO servers(id,name,owner_id,created_at,description,is_public) VALUES(?,?,?,?,?,0)').run(id, 'Glean', 3, 'different-date', 'A user-owned server');
assert.equal(service.isServer(id), false);
assert.equal(service.isRequiredChannel(channel.id), false);
service.enroll(4);
assert.equal(db.prepare('SELECT count(*) n FROM server_members').get().n, 0);
db.exec("INSERT INTO users VALUES(5,'Nuper')");
const restoredId = service.ensureAll();
assert.notEqual(restoredId, id);
assert.equal(db.prepare('SELECT count(*) n FROM servers').get().n, 2);
assert.equal(db.prepare('SELECT count(*) n FROM server_members WHERE server_id=?').get(restoredId).n, 4);
db.close();
console.log('Official Glean enrollment, kick/ban exclusions, invite rejoin, restart idempotency, account deletion, and ID reuse tests passed.');
