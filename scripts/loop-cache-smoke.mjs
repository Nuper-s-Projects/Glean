import assert from 'node:assert/strict';
import { createLoopCache } from '../src/app/loopCache.js';

let clock = 0, requests = 0;
const cache = createLoopCache({ now: () => clock, ttl: 100, maxEntries: 2, maxBytes: 1000 });
cache.setAccount(1);
const fetcher = async () => ({ version: ++requests });
const [a, b] = await Promise.all([cache.read('/a', fetcher), cache.read('/a', fetcher)]);
assert.equal(a, b); assert.equal(requests, 1, 'concurrent requests are shared');
assert.equal((await cache.read('/a', fetcher)).version, 1);
clock = 100; assert.equal((await cache.read('/a', fetcher)).version, 2, 'expired metadata is reloaded');
assert.equal((await cache.read('/a', fetcher, { force: true })).version, 3);
await cache.read('/b', fetcher); cache.peek('/a'); await cache.read('/c', fetcher);
assert.equal(cache.peek('/b'), null, 'least recently used entry evicted');
cache.setAccount(2); assert.equal(cache.peek('/a'), null, 'accounts never share entries');
let resolveOld;
const old = cache.read('/race', () => new Promise(resolve => { resolveOld = resolve; }));
await Promise.resolve(); cache.setAccount(3); resolveOld({ old: true });
await assert.rejects(old, { name: 'AbortError' }); assert.equal(cache.peek('/race'), null);
let resolveSlow, calls = 0;
const mutateRace = cache.read('/mutate', () => ++calls === 1 ? new Promise(resolve => { resolveSlow = resolve; }) : { updated: true });
await Promise.resolve(); cache.invalidate(); resolveSlow({ updated: false });
assert.deepEqual(await mutateRace, { updated: true }, 'a late response cannot restore deleted/edited data');
let resolveUnrelated;
const unrelated = cache.read('/profile', () => new Promise(resolve => { resolveUnrelated = resolve; }));
await Promise.resolve(); cache.invalidate(key => key.startsWith('/posts')); resolveUnrelated({ profile: true });
assert.deepEqual(await unrelated, { profile: true }); assert.ok(cache.peek('/profile'), 'post changes do not restart unrelated profile requests');
let resolveShared;
const controller = new AbortController();
const one = cache.read('/shared', () => new Promise(resolve => { resolveShared = resolve; }), { signal: controller.signal });
const two = cache.read('/shared', fetcher); await Promise.resolve(); controller.abort();
await assert.rejects(one, { name: 'AbortError' }); resolveShared({ shared: true }); assert.deepEqual(await two, { shared: true });
await cache.read('/oversized', () => ({ data: 'x'.repeat(1000) })); assert.equal(cache.peek('/oversized'), null);
let failures = 0;
await assert.rejects(cache.read('/failure', () => { failures++; throw new Error('offline'); }));
await assert.rejects(cache.read('/failure', () => { failures++; throw new Error('offline'); }));
assert.equal(failures, 2, 'failed responses are not cached');
cache.setAccount(null); await cache.read('/anonymous', fetcher); assert.equal(cache.peek('/anonymous'), null);
console.log('PASS Loop metadata cache: deduplication, TTL, forced refresh, LRU/byte bounds, account clearing, mutation races, independent aborts, errors, anonymous bypass.');
